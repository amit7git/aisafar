/* Small stable hash so every classic bumper keeps ONE emoji across moments. */
function hashLine(text) {
    let h = 0;
    for (let i = 0; i < text.length; i++) {
        h = (h * 31 + text.charCodeAt(i)) >>> 0;
    }
    return h;
}

/* Classic bumpers predate the emoji rule — decorate them at display time with
   a relatable highway/truck emoji so every displayed line still carries one. */
const CLASSIC_EMOJIS = ["🚛", "🛣️", "📻", "🚦", "🚚", "🚧", "⚙️", "🎙️", "🚜", "⛽"];
function decorateClassic(text) {
    if (/\p{Extended_Pictographic}/u.test(text)) return text;
    return CLASSIC_EMOJIS[hashLine(text) % CLASSIC_EMOJIS.length] + " " + text;
}

function pushWeighted(pool, lines, weight, decorate) {
    if (!Array.isArray(lines) || !lines.length) return;
    for (const raw of lines) {
        const line = decorate ? decorate(raw) : raw;
        for (let i = 0; i < weight; i++) pool.push(line);
    }
}

/**
 * Build a display pool for the current context.
 *
 * @param {object} ctx
 * @param {string} ctx.mood        current Safar key (MOOD_PLAYLISTS key)
 * @param {string[]} ctx.tags      playlist tags (from playlist metadata)
 * @param {string[]} ctx.atmosphere live context (e.g. ["night"], ["rain"])
 * @returns {string[]}             weighted, context-relevant bumper pool
 */
export function buildBumperPool({ mood = "", tags = [], atmosphere = [] } = {}) {
    const pool = [];

    // 1. Dedicated lines for the current Safar (highest preference)
    pushWeighted(pool, SAFAR_BUMPERS[mood], 3);

    // 2. Atmosphere categories resolved from playlist tags (graceful fallback
    //    for playlists that have no dedicated entry yet)
    const tagCats = [];
    for (const tag of tags) {
        const cat = TAG_CATEGORIES[tag];
        if (cat && !tagCats.includes(cat)) tagCats.push(cat);
    }
    for (const cat of tagCats) pushWeighted(pool, ATMOSPHERE_BUMPERS[cat], 2);

    // 3. Live atmosphere state (night, rain, …)
    for (const cat of atmosphere) pushWeighted(pool, ATMOSPHERE_BUMPERS[cat], 3);

    // 4. Universal Radio Safar lines
    pushWeighted(pool, UNIVERSAL_BUMPERS, 2);

    // 5. Existing classic bumpers (preserved, emoji-decorated)
    pushWeighted(pool, BUMPERS, 1, decorateClassic);

    return pool;
}

