/**
 * Radio Safar — Layered, context-aware bumper library.
 *
 * The bumper engine is built in layers so future playlists work with zero code
 * changes:
 *
 *   A. Universal Radio Safar bumpers      → every playlist, always relevant
 *   B. Safar-specific bumpers             → keyed by existing MOOD_PLAYLISTS keys
 *   C. Atmosphere/context bumpers         → travel, highway, truck, night, rain,
 *                                          chai, nostalgia, romantic, music,
 *                                          funny, general radio, सफ़र साथी
 *
 * The selector (`buildBumperPool`) resolves, in order of preference:
 *   1. dedicated lines for the CURRENT Safar
 *   2. atmosphere categories matched from playlist `tags`
 *   3. live atmosphere state (night, rain, …) supplied by the caller
 *   4. universal Radio Safar lines
 *   5. the existing classic bumpers (preserved in bumpers.js, decorated with a
 *      relatable emoji at display time so every displayed line carries one)
 *
 * Playlists that have no dedicated entry yet simply fall back to tag-matched
 * and universal lines — they never borrow another region's lines.
 *
 * Every curated line contains a relevant emoji and stays short enough for the
 * one-line player placard.
 */

